clear; close all;
rf = @(t, t0, tp, peak, rec, base) base + (t >= t0 & t < tp) .* peak .* (3 * ((t - t0) / (tp - t0)).^2 - 2 * ((t - t0) / (tp - t0)).^3) ...
     + (t >= tp) .* (peak .* exp(-(t - tp) / rec));
